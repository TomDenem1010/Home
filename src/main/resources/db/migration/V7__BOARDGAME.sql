CREATE TABLE BOARD_GAME (
    ID VARCHAR2(255) PRIMARY KEY,
    NAME VARCHAR2(255 CHAR) NOT NULL,
    BGG_LINK VARCHAR2(1000 CHAR),
    STATE VARCHAR2(16) NOT NULL,
    TYPE VARCHAR2(32) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_MODIFIED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(255) DEFAULT 'system' NOT NULL,
    LAST_MODIFIED_BY VARCHAR2(255) DEFAULT 'system' NOT NULL,
    CONSTRAINT CK_BOARD_GAME_STATE CHECK (STATE IN ('OWN', 'SOLD')),
    CONSTRAINT CK_BOARD_GAME_TYPE CHECK (TYPE IN ('BASE', 'EXPANSION', 'BASE_AND_EXPANSION'))
);
CREATE TABLE BOARD_GAME_PLAY (
    ID VARCHAR2(255) PRIMARY KEY,
    BOARD_GAME_ID VARCHAR2(255) NOT NULL,
    PLAYED_AT TIMESTAMP(6) NOT NULL,
    RATING NUMBER(1) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_MODIFIED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(255) DEFAULT 'system' NOT NULL,
    LAST_MODIFIED_BY VARCHAR2(255) DEFAULT 'system' NOT NULL,
    CONSTRAINT FK_BOARD_GAME_PLAY_GAME FOREIGN KEY (BOARD_GAME_ID) REFERENCES BOARD_GAME(ID),
    CONSTRAINT CK_BOARD_GAME_PLAY_RATING CHECK (RATING BETWEEN 1 AND 5)
);
CREATE INDEX IX_BOARD_GAME_NAME ON BOARD_GAME (NAME);
CREATE INDEX IX_BOARD_GAME_PLAY_GAME ON BOARD_GAME_PLAY (BOARD_GAME_ID);
CREATE INDEX IX_BOARD_GAME_PLAY_TIME ON BOARD_GAME_PLAY (PLAYED_AT);
