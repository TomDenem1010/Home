CREATE TABLE MEDIA_VIDEO_TAG (
    ID VARCHAR2(255) PRIMARY KEY,
    NAME VARCHAR2(255 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_MODIFIED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(255) DEFAULT 'system' NOT NULL,
    LAST_MODIFIED_BY VARCHAR2(255) DEFAULT 'system' NOT NULL,
    CONSTRAINT UQ_MEDIA_VIDEO_TAG_NAME UNIQUE (NAME)
);
CREATE TABLE MEDIA_VIDEO_TAG_ASSIGNMENT (
    VIDEO_ID VARCHAR2(255) NOT NULL,
    TAG_ID VARCHAR2(255) NOT NULL,
    CONSTRAINT PK_MEDIA_VIDEO_TAG_ASSIGNMENT PRIMARY KEY (VIDEO_ID, TAG_ID),
    CONSTRAINT FK_MEDIA_VT_VIDEO FOREIGN KEY (VIDEO_ID) REFERENCES MEDIA_VIDEO(ID),
    CONSTRAINT FK_MEDIA_VT_TAG FOREIGN KEY (TAG_ID) REFERENCES MEDIA_VIDEO_TAG(ID)
);
CREATE INDEX IX_MEDIA_VT_TAG ON MEDIA_VIDEO_TAG_ASSIGNMENT (TAG_ID);
